void matmul_top(data_t A[N][N], data_t B[N][N], data_t C[N][N])
{
    // 给循环命名（标签），便于�??? GUI 中定向添加优化指�???
    I: for (int i = 0; i < N; i++)
    {
        J: for (int j = 0; j < N; j++)
        {
        	data_t sum = 0;
            K: for (int k = 0; k < N; k++)
            {
                // 每次迭代�???1 次乘�??? + 1 次加法（MAC�???
                sum += A[i][k] * B[k][j];
            }
            C[i][j] = sum;
        }
    }
}
